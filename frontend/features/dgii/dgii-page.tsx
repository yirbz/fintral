function FieldInput({ label, value, onChange, type = "text", placeholder }: {
  label: string; value: string | number | null | undefined;
  onChange: (v: string) => void; type?: string; placeholder?: string;
}) {
  return (
    <div className="flex flex-col gap-0.5">
      <label className="text-[9px] font-semibold uppercase tracking-wider text-muted-foreground">{label}</label>
      <Input
        type={type}
        value={value ?? ""}
        onChange={e => onChange(e.target.value)}
        className="h-7 text-xs font-mono"
        placeholder={placeholder}
        onClick={e => e.stopPropagation()}
      />
    </div>
  );
}

function FieldSelect({ label, value, onChange, options }: {
  label: string; value: string | null | undefined;
  onChange: (v: string) => void;
  options: { value: string; label: string }[];
}) {
  const hasValueOption = !!value && options.some((option) => option.value === value);
  const resolvedOptions = !hasValueOption && value
    ? [{ value, label: value }, ...options]
    : options;

  return (
    <div className="flex flex-col gap-0.5" role="presentation" onClick={e => e.stopPropagation()}>
      <label className="text-[9px] font-semibold uppercase tracking-wider text-muted-foreground">{label}</label>
      <Select value={value || ""} onValueChange={onChange}>
        <SelectTrigger className="h-7 text-xs">
          <SelectValue placeholder="Seleccionar..." />
        </SelectTrigger>
        <SelectContent>
          <SelectItem value="__none">— Sin valor —</SelectItem>
          {resolvedOptions.length > 0
            ? resolvedOptions.map((option) => (
              <SelectItem key={option.value} value={option.value}>
                {option.label}
              </SelectItem>
            ))
            : (
              <SelectItem value="__empty" disabled>
                Sin opciones disponibles
              </SelectItem>
            )}
        </SelectContent>
      </Select>
    </div>
  );
}

