// ── Date input with DD-MM-YYYY display + native picker ─────────────────

function DgiiDateInput({ value, onChange, placeholder, className }: {
  value: string;
  onChange: (v: string) => void;
  placeholder?: string;
  className?: string;
}) {
  const [text, setText] = useState(value ? value.split("-").reverse().join("-") : "");
  const pickerRef = useRef<HTMLInputElement>(null);
  const committed = useRef(true);

  // Sync from external (picker) changes
  useEffect(() => {
    if (committed.current) {
      setText(value ? value.split("-").reverse().join("-") : "");
    }
  }, [value]);

  const handleTextChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    committed.current = false;
    const raw = e.target.value.replace(/[^0-9]/g, "");
    let formatted = raw;
    if (raw.length > 2) formatted = raw.slice(0, 2) + "-" + raw.slice(2);
    if (raw.length > 4) formatted = formatted.slice(0, 5) + "-" + formatted.slice(5);
    setText(formatted);
    // Auto-commit when complete dd-mm-yyyy
    if (/^\d{2}-\d{2}-\d{4}$/.test(formatted)) {
      const [d, m, y] = formatted.split("-");
      committed.current = true;
      onChange(`${y}-${m}-${d}`);
    }
  };

  return (
    <div className={cn("relative", className)}>
      <Calendar
        className="absolute left-2 top-1/2 size-3 -translate-y-1/2 text-muted-foreground cursor-pointer"
        onClick={() => pickerRef.current?.showPicker()}
      />
      <input
        type="text"
        value={text}
        onChange={handleTextChange}
        placeholder={placeholder || "DD-MM-YYYY"}
        className="flex h-8 w-full rounded-md border border-input bg-transparent pl-7 pr-2 text-xs shadow-xs transition-[color,box-shadow] outline-none placeholder:text-muted-foreground/50 disabled:pointer-events-none disabled:cursor-not-allowed disabled:opacity-50"
        onFocus={(e) => { const inp = e.target; setTimeout(() => inp.select(), 0); }}
      />
      <input
        ref={pickerRef}
        type="date"
        value={value}
        onChange={(e) => { committed.current = true; onChange(e.target.value); }}
        className="absolute inset-0 opacity-0 pointer-events-none"
        tabIndex={-1}
        aria-hidden
      />
    </div>
  );
}

