function currentPeriod() {
  const now = new Date();
  return `${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, "0")}`;
}

function periodLabel(p: string) {
  const months = ["Enero", "Febrero", "Marzo", "Abril", "Mayo", "Junio", "Jul", "Agosto", "Sep", "Octubre", "Nov", "Diciembre"];
  const y = p.slice(0, 4), m = parseInt(p.slice(4, 6), 10) - 1;
  return `${months[m]} ${y}`;
}

function prevPeriod(p: string) {
  let y = parseInt(p.slice(0, 4)), m = parseInt(p.slice(4, 6));
  m--; if (m < 1) { m = 12; y--; }
  return `${y}${String(m).padStart(2, "0")}`;
}
function nextPeriod(p: string) {
  let y = parseInt(p.slice(0, 4)), m = parseInt(p.slice(4, 6));
  m++; if (m > 12) { m = 1; y++; }
  return `${y}${String(m).padStart(2, "0")}`;
}

